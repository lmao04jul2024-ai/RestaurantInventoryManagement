// Adds Testing Library's DOM assertions (toBeInTheDocument etc.) to every spec.
import '@testing-library/jest-dom';

// jsdom lacks this guard some libs expect when persisting to localStorage.
if (!window.matchMedia) {
  Object.defineProperty(window, 'matchMedia', {
    writable: true,
    value: (query: string) => ({
      matches: false,
      media: query,
      onchange: null,
      addListener: () => {},
      removeListener: () => {},
      addEventListener: () => {},
      removeEventListener: () => {},
      dispatchEvent: () => false,
    }),
  });
}
